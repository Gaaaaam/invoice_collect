# 常见方向词后缀
_DIR_SUFFIX = re.compile(r"[东南西北]站?$")
# 行政区划后缀
_ADMIN_SUFFIX = re.compile(r"(市|区|县|省|自治区|特别行政区|站)$")
# 机场关键词
_AIRPORT_KW = re.compile(r"(国际机场|机场|国内机场)")
# 车站关键词
_STATION_KW = re.compile(r"(站|高铁站|火车站)")
# 航站楼后缀，如「绵阳 南郊 T2」「上海浦东T1」
_TERMINAL_BUILD = re.compile(r"\s*[Tt]\d\b\s*")


def station_to_city(raw: Optional[str]) -> str:
    """
    将发票上的车站/机场/港口/城市名称转换为标准城市名。
    优先级：
      1. 精确匹配映射字典
      2. 去掉空白后精确匹配（如「上海 浦东」→「上海浦东」）
      3. 处理机票行程单的 "城市-机场简称" 格式（取 '-' 前的城市部分）
      4. 去掉站/机场等后缀再匹配
      5. 从映射字典中找包含关系
      6. 去掉行政区划后缀后直接返回
    """
    if not raw:
        return ""
    text = raw.strip()
    # 去掉航站楼代号（如「绵阳 南郊 T2」），便于与映射表匹配
    text = re.sub(r"\s*[Tt]\d\b", "", text).strip()
    text = re.sub(r"\s+", " ", text)
    compact = re.sub(r"\s+", "", text)

    # 1. 精确匹配
    if text in STATION_TO_CITY:
        return STATION_TO_CITY[text]
    if compact != text and compact in STATION_TO_CITY:
        return STATION_TO_CITY[compact]

    # 2. 机票行程单 "城市-机场" 格式，如 "福州-长乐" / "上海-浦东"
    if "-" in text:
        city_part = text.split("-")[0].strip()
        if city_part in STATION_TO_CITY:
            return STATION_TO_CITY[city_part]
        # 城市本身即标准城市名
        city_clean = _ADMIN_SUFFIX.sub("", city_part)
        if city_clean:
            return city_clean

    # 3. 去掉机场/车站后缀再精确匹配
    stripped = _AIRPORT_KW.sub("", text).strip()
    stripped = _STATION_KW.sub("", stripped).strip()
    if stripped in STATION_TO_CITY:
        return STATION_TO_CITY[stripped]
    if stripped and stripped != text:
        # 再查映射
        for key, city in STATION_TO_CITY.items():
            if stripped == _STATION_KW.sub("", _AIRPORT_KW.sub("", key)).strip():
                return city

    # 4. 包含关系模糊匹配（优先匹配更长的 key）
    matches = [(k, v) for k, v in STATION_TO_CITY.items() if k in text or text in k]
    if matches:
        # 选最长匹配的 key 作为最精确结果
        best = max(matches, key=lambda x: len(x[0]))
        return best[1]

    # 5. 直接去掉行政区划/站后缀当城市名
    cleaned = _ADMIN_SUFFIX.sub("", text)
    cleaned = _DIR_SUFFIX.sub("", cleaned)
    return cleaned or text


def normalize_transport_city(city_raw: Optional[str]) -> str:
    """
    对外暴露的标准化入口：将发票字段中的出发/到达地点统一到城市级别。
    """
    if not city_raw:
        return ""
    result = station_to_city(city_raw)
    # 最终去掉可能残留的行政区划后缀
    result = re.sub(r"(市|区|县)$", "", result)
    return result.strip()
